"""End-to-end smoke test: run every example request through the full agent.

    python scripts/run_smoke_tests.py                  # deterministic mode, prints a result table, exit 1 on mismatch
    python scripts/run_smoke_tests.py --write-examples # also (re)generate examples/sample_requests.md and
                                                       # examples/expected_outputs.md from the REAL outputs
    python scripts/run_smoke_tests.py --mode auto      # use the LLM when OPENAI_API_KEY is set (costs tokens)

Each example in data/specs/*.yaml declares the state it must end in ("executed" or
"needs_input"); a mismatch is a failure. Nothing is hard-coded here: the markdown files
are produced from the execution records.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.agent import Agent  # noqa: E402
from src.config import Settings  # noqa: E402
from src.models import AgentResponse, Attachment, StepStatus  # noqa: E402
from src.result_formatter import table_to_markdown  # noqa: E402


def make_agent(mode: str, out_dir: Path) -> Agent:
    s = Settings.from_env().with_overrides(llm_mode=mode, output_dir=out_dir, retry_backoff_scale=0)
    return Agent(s, audit=False)


def fmt_scalar(v) -> str:
    return json.dumps(v, ensure_ascii=False, default=str) if isinstance(v, (dict, list)) else str(v)


def render_result(data: dict) -> str:
    lines = []
    for k, v in data.items():
        label = k.replace("_", " ")
        if isinstance(v, list) and v and isinstance(v[0], dict):
            lines.append(f"- **{label}** ({len(v)}):\n\n{table_to_markdown(v, limit=6)}\n")
        elif isinstance(v, str) and "\n" in v:
            lines.append(f"- **{label}**:\n\n```text\n{v}\n```\n")
        elif isinstance(v, dict) and any(isinstance(x, (dict, list)) for x in v.values()):
            lines.append(f"- **{label}**: `{json.dumps(v, ensure_ascii=False, default=str)[:300]}`")
        else:
            lines.append(f"- **{label}**: {fmt_scalar(v)}")
    return "\n".join(lines)


def render_example(ex: dict, resp: AgentResponse) -> str:
    out = [f"### {ex['workflow_id']} · {ex['title']}", "", f"> {ex['request']}", ""]
    if ex["attachments"]:
        out += [f"Attached: {', '.join(f'`{a}`' for a in ex['attachments'])}", ""]
    r = resp.routing
    out.append(f"- **Routing** ({r.mode}): `{r.workflow_id}` — {r.explanation}")
    if resp.resolution:
        shown = {k: v for k, v in resp.resolution.values.items() if v is not None and resp.resolution.sources.get(k) != "default"}
        out.append(f"- **Extracted inputs:** `{json.dumps(shown, ensure_ascii=False, default=str)}`" if shown else "- **Extracted inputs:** none (defaults only)")
    out.append(f"- **Outcome:** `{resp.state}` — {resp.message.splitlines()[0]}")
    if ex.get("note"):
        out.append(f"- **Note:** {ex['note']}")
    rec = resp.record
    if rec:
        out += ["", f"Status: **{rec.status.value}** · {len(rec.completed_step_ids)} of {len(rec.steps)} steps completed", "",
                "| # | Step | Tool | Status | Result |", "|---|---|---|---|---|"]
        for i, s in enumerate(rec.steps, 1):
            tool = f"`{s.tool}`{' (simulated)' if s.simulated else ''}" if s.tool else "decision"
            res = (s.output_summary or s.note or s.skipped_reason or "").replace("|", "/")
            res = (res[:90] + "…") if len(res) > 90 else res
            out.append(f"| {i} | {s.name} | {tool} | {s.status.value} | {res} |")
        conds = [c for c in rec.conditions if c.result is not None or c.rows_evaluated is not None]
        if conds:
            out += ["", "Conditions evaluated:", ""]
            for c in conds[:8]:
                res = "" if c.result is None else f" → **{'true' if c.result else 'false'}**"
                rows = f" ({c.rows_matched} of {c.rows_evaluated} rows matched)" if c.rows_evaluated is not None else ""
                out.append(f"- `{c.expression}`{res}{rows} — {c.label}")
        for e in rec.errors:
            out.append(f"- error [{e.category.value}]: {e.message}")
        if rec.final_result:
            fr = rec.final_result
            out += ["", f"**Final result** — {fr.headline}", ""]
            out += [f"> ⚠ {w}" for w in fr.warnings]
            out += ["", render_result(fr.data)]
    out.append("")
    return "\n".join(out)


def render_sample_requests(agent: Agent) -> str:
    out = ["# Sample requests", "",
           "_Generated by `python scripts/run_smoke_tests.py --write-examples` from `data/specs/*.yaml` and the workbook's `Test_Questions` sheet._", "",
           "Type any of these into the app (or pick it from the **Example requests** dropdown). Requests marked 📎 need the sample file attached "
           "(choose it under *…or use a sample file*). Rows marked **asks** deliberately lack information: the agent must ask for it instead of guessing.", ""]
    for d in agent.registry.all():
        if d.is_extension:
            continue
        out += [f"## {d.id} · {d.name}", "", f"*Excel trigger:* {d.triggers[0]}  ", f"*What is checked (Excel Test_Questions):* "
                + "; ".join(t.what_to_check for t in d.test_requests), "", "| Request | Needs | Expected |", "|---|---|---|"]
        for ex in d.examples:
            att = f"📎 `{'`, `'.join(ex.attachments)}`" if ex.attachments else "—"
            exp = "**asks** for the missing information" if ex.expect_state == "needs_input" else "runs to completion"
            out.append(f"| {ex.request.replace('|', '/')} | {att} | {exp} |")
        out.append("")
    return "\n".join(out)


EXPECTED_HEADER = ["# Expected outputs", "",
                   "_Generated by `python scripts/run_smoke_tests.py --write-examples` by actually running every example through the agent "
                   "in **deterministic mode** (no LLM, no network). Durations and run IDs are omitted so the file is reproducible. "
                   "With an OpenAI key the routing/extraction would be done by the model and the generated wording of WF004/WF007 would differ; "
                   "the business results (counts, flags, rankings) do not depend on the model._", "",
                   "All data comes from `data/fixtures` (simulated systems).", ""]


def run_examples(agent: Agent, *, echo: bool = False) -> tuple[list[str], int]:
    """Run every example through the agent. Returns (markdown sections, number of mismatches)."""
    sections, failures = [], 0
    for ex in agent.examples():
        atts = [Attachment(name=a, path=a) for a in ex["attachments"]]
        resp = agent.handle(ex["request"], attachments=atts)
        routed = resp.routing.workflow_id if resp.routing else None
        ok = resp.state == ex["expect_state"] and routed == ex["workflow_id"]
        failures += not ok
        if echo:
            print(f"{ex['workflow_id']:<6} {ex['expect_state']:<12} {resp.state:<12} {routed or '-':<7} {ex['request'][:70]}  {'OK' if ok else '<-- MISMATCH'}")
        sections.append(render_example(ex, resp))
    return sections, failures


def build_documents(agent: Agent) -> tuple[str, str]:
    """(sample_requests.md, expected_outputs.md) text for the given deterministic agent."""
    sections, _ = run_examples(agent)
    return render_sample_requests(agent) + "\n", "\n".join(EXPECTED_HEADER + sections) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mode", default="deterministic", choices=["deterministic", "auto", "llm"])
    ap.add_argument("--write-examples", action="store_true")
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        agent = make_agent(args.mode, Path(tmp) / "outputs")
        info = agent.mode_info()
        print(f"Mode: {info['effective_mode']} — {info['reason']}")
        print(f"Catalog: {agent.registry.report.status_label}\n")
        print(f"{'WF':<6} {'expected':<12} {'got':<12} {'routed':<7} request")
        sections, failures = run_examples(agent, echo=True)

        if args.write_examples:
            if args.mode != "deterministic":
                print("\n--write-examples needs --mode deterministic so the files are reproducible.")
                return 2
            (ROOT / "examples").mkdir(exist_ok=True)
            (ROOT / "examples" / "sample_requests.md").write_text(render_sample_requests(agent) + "\n", encoding="utf-8")
            (ROOT / "examples" / "expected_outputs.md").write_text("\n".join(EXPECTED_HEADER + sections) + "\n", encoding="utf-8")
            print("\nwrote examples/sample_requests.md and examples/expected_outputs.md")
        print(f"\n{len(sections) - failures}/{len(sections)} examples behaved as specified")
        return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
