"""Validate the workflow catalog and (optionally) regenerate the derived artefacts.

    python scripts/validate_workflows.py            # print the validation report, exit 1 if unhealthy
    python scripts/validate_workflows.py --write    # also rewrite data/normalized_workflows.json
                                                    # and docs/validation_report.md

The report answers: were all 10 workflows extracted from the workbook, and does every
one of them trace back to the Excel text (steps, inputs, tools), reference only registered
tools and existing step outputs, and define its conditions with valid expressions?
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.config import REQUIRED_WORKFLOW_IDS, Settings  # noqa: E402
from src.tools import build_default_registry  # noqa: E402
from src.workflow_registry import WorkflowRegistry  # noqa: E402


def build_markdown(reg: WorkflowRegistry) -> str:
    rep = reg.report
    excel = reg.excel_catalogs()[0]
    lines = [
        "# Workflow validation report",
        "",
        "_Generated by `scripts/validate_workflows.py --write`. Do not edit by hand._",
        "",
        f"- **Result:** {'PASS' if rep.ok else 'FAIL'} - {rep.status_label}",
        f"- **Workbook:** `{Path(excel.path).name}` (SHA-256 `{rep.workbook_sha256}`)",
        f"- **Sheets:** " + "; ".join(f"`{s.name}` -> {s.role} ({s.rows_read} rows, header row {s.header_row})" for s in rep.sheets),
        f"- **Required workflows registered:** {len(REQUIRED_WORKFLOW_IDS) - len(rep.missing_ids)}/{len(REQUIRED_WORKFLOW_IDS)}",
        f"- **Tools registered:** {len(reg.tools.names())}",
        f"- **Issues:** {len(rep.errors)} error(s), {len(rep.warnings)} warning(s)",
        "",
        "## Per-workflow extraction and validation",
        "",
        "| ID | Name | Excel steps | Executable steps | Excel inputs | Declared inputs | Excel tools -> registered tools | Conditions | Status |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for wid in REQUIRED_WORKFLOW_IDS:
        if not reg.has(wid):
            lines.append(f"| {wid} | - | - | - | - | - | - | - | **NOT REGISTERED** |")
            continue
        d = reg.get(wid)
        tools = "; ".join(f"{k} -> {', '.join(v)}" for k, v in d.tool_map.items())
        lines.append(f"| {d.id} | {d.name} | {len(d.excel_steps)} | {len(d.steps)} | {len(d.excel_inputs)} | {len(d.inputs)} | {tools} | {len(d.conditions)} | valid |")
    lines += ["", "## Checks performed on every workflow", "",
              "1. Workflow ID present, unique, well-formed; name and steps not empty.",
              "2. The spec's `excel_step` sequence equals the workbook's Steps cell (order and wording).",
              "3. Every Excel input phrase is covered by a declared input or data source, and the spec covers nothing the workbook does not say.",
              "4. Every Excel tool phrase maps to registered tools, and every step's tool is mapped or a core utility.",
              "5. Tool parameters exist in the tool's input schema; required parameters are present.",
              "6. Every expression, template, row rule and post-condition parses with the safe evaluator.",
              "7. `inputs.x` is declared; `steps.y` runs earlier and `y`'s tool really outputs the referenced field.",
              "8. Branch targets exist and only jump forward; `end` outcomes are defined; non-default outcomes only use steps that have run.",
              "9. Referenced example attachments exist."]
    if rep.issues:
        lines += ["", "## Issues", ""] + [f"- **{i.severity.upper()}** {i.workflow_id or 'catalog'}: {i.message}" for i in rep.issues]
    else:
        lines += ["", "## Issues", "", "None."]
    lines += ["", "## Ambiguities found in the workbook and how they were interpreted", ""]
    for wid in REQUIRED_WORKFLOW_IDS:
        if reg.has(wid):
            d = reg.get(wid)
            lines.append(f"### {d.id} - {d.name}")
            lines += [f"- {n}" for n in d.interpretation_notes] or ["- (none)"]
            lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="rewrite data/normalized_workflows.json and docs/validation_report.md")
    args = ap.parse_args()

    settings = Settings.from_env(load_dotenv_file=False)
    reg = WorkflowRegistry(settings, build_default_registry())
    rep = reg.load()

    print(f"Catalog: {rep.status_label}")
    for wid in REQUIRED_WORKFLOW_IDS:
        if reg.has(wid):
            d = reg.get(wid)
            print(f"  [ok] {d.id} {d.name:<32} steps {len(d.excel_steps)}->{len(d.steps):<2} inputs {len(d.inputs)} conditions {len(d.conditions)} tools {', '.join(d.allowed_tools)}")
        else:
            print(f"  [!!] {wid} NOT REGISTERED")
    for i in rep.issues:
        print(f"  {i.severity.upper()}: {i.workflow_id or 'catalog'}: {i.message}")

    if args.write and rep.ok:
        out = ROOT / "data" / "normalized_workflows.json"
        out.write_text(json.dumps(json.loads(json.dumps(reg.normalized_catalog(), default=str)), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (ROOT / "docs").mkdir(exist_ok=True)
        (ROOT / "docs" / "validation_report.md").write_text(build_markdown(reg) + "\n", encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)} and docs/validation_report.md")
    elif args.write:
        print("not writing artefacts: the catalog is not healthy")
    return 0 if rep.ok else 1


if __name__ == "__main__":
    sys.exit(main())
