"""Central tool registry.

Every capability a workflow step can use is a :class:`ToolSpec` registered here
with a name, description, Pydantic input/output schemas and an execution
function. The engine resolves a step's ``tool`` through this registry and the
registry validates the parameters *before* and the output *after* every call.

Tools never see the engine, the workflow definition or the LLM router: they
get validated parameters and a small :class:`ToolContext`.
"""

from __future__ import annotations

import fnmatch
import logging
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any, Callable, Literal

from pydantic import BaseModel, ValidationError

from .config import Settings
from .errors import ToolParameterError, UnexpectedToolOutput, UnknownToolError, TransientToolError, ToolExecutionError
from .models import ToolInfo

if TYPE_CHECKING:  # pragma: no cover
    from .llm import LLMBackend
    from .tools.data_access import DataAccess

log = logging.getLogger(__name__)

ToolKind = Literal["local_data", "simulated_api", "computation", "llm", "file_output"]


class FaultInjector:
    """Deterministic failure injection for the *simulated* APIs.

    Used by tests and by the UI's "simulate an outage" switch so retry and
    partial-completion behaviour can be demonstrated on demand. Armed faults
    are consumed one per call, in order.
    """

    def __init__(self) -> None:
        self._queued: dict[str, list[Exception]] = {}
        self.history: list[tuple[str, str]] = []

    def arm(self, tool: str, errors: list[Exception]) -> None:
        self._queued.setdefault(tool, []).extend(errors)

    def arm_transient(self, tool: str, times: int = 1, message: str = "Simulated upstream timeout") -> None:
        self.arm(tool, [TransientToolError(message) for _ in range(times)])

    def arm_terminal(self, tool: str, message: str = "Simulated upstream failure") -> None:
        self.arm(tool, [ToolExecutionError(message)])

    def pending(self, tool: str | None = None) -> int:
        if tool:
            return len(self._queued.get(tool, []))
        return sum(len(v) for v in self._queued.values())

    def clear(self) -> None:
        self._queued.clear()

    def check(self, tool: str) -> None:
        queue = self._queued.get(tool)
        if queue:
            err = queue.pop(0)
            self.history.append((tool, type(err).__name__))
            raise err


@dataclass
class ToolContext:
    """Per-call context handed to tool functions."""

    settings: Settings
    data: "DataAccess"
    faults: FaultInjector = field(default_factory=FaultInjector)
    llm: "LLMBackend | None" = None
    run_id: str = ""
    step_id: str | None = None
    attempt: int = 1
    #: tools call this to report a row-level rule evaluation to the trace
    condition_sink: Callable[[dict[str, Any]], None] | None = None
    #: tools append notes to be shown in the trace (e.g. "generated by template")
    notes: list[str] = field(default_factory=list)

    def record_condition(self, **kwargs: Any) -> None:
        if self.condition_sink:
            self.condition_sink(kwargs)


@dataclass
class ToolSpec:
    name: str
    description: str
    input_model: type[BaseModel]
    output_model: type[BaseModel]
    func: Callable[[Any, ToolContext], dict | BaseModel]
    kind: ToolKind = "computation"
    simulated: bool = False
    side_effect: bool = False
    idempotent: bool = True
    #: usable by every workflow without being listed in its Excel Tools_Required
    core: bool = False
    #: glob patterns (over the param path) of params holding *row expressions*
    #: that must be passed through unevaluated, e.g. ``["where", "derive.*"]``
    expression_params: tuple[str, ...] = ()

    @property
    def retry_allowed(self) -> bool:
        """Retrying a transient failure is only safe for tools without
        non-idempotent side effects."""
        return (not self.side_effect) or self.idempotent

    def is_expression_param(self, path: str) -> bool:
        return any(fnmatch.fnmatchcase(path, pat) for pat in self.expression_params)

    def info(self) -> ToolInfo:
        return ToolInfo(
            name=self.name,
            description=self.description,
            kind=self.kind,
            simulated=self.simulated,
            side_effect=self.side_effect,
            idempotent=self.idempotent,
            core=self.core,
            expression_params=list(self.expression_params),
            input_schema=self.input_model.model_json_schema(),
            output_schema=self.output_model.model_json_schema(),
        )

    def output_fields(self) -> set[str]:
        return set(self.output_model.model_fields)

    def input_fields(self) -> dict[str, Any]:
        return dict(self.input_model.model_fields)


class ToolRegistry:
    def __init__(self) -> None:
        self._tools: dict[str, ToolSpec] = {}

    # ------------------------------------------------------------ registration
    def register(self, spec: ToolSpec) -> ToolSpec:
        if spec.name in self._tools:
            raise ValueError(f"Tool '{spec.name}' is already registered")
        self._tools[spec.name] = spec
        return spec

    # ------------------------------------------------------------------ lookup
    def has(self, name: str) -> bool:
        return name in self._tools

    def get(self, name: str) -> ToolSpec:
        try:
            return self._tools[name]
        except KeyError:
            raise UnknownToolError(
                f"Tool '{name}' is not registered. Registered tools: {', '.join(sorted(self._tools))}",
                code="unknown_tool",
            ) from None

    def names(self) -> list[str]:
        return sorted(self._tools)

    def specs(self) -> list[ToolSpec]:
        return [self._tools[n] for n in self.names()]

    def infos(self) -> list[ToolInfo]:
        return [s.info() for s in self.specs()]

    # --------------------------------------------------------------- execution
    def execute(self, name: str, params: dict[str, Any], ctx: ToolContext) -> dict[str, Any]:
        """Validate ``params``, run the tool, validate and return its output."""
        spec = self.get(name)
        try:
            parsed = spec.input_model.model_validate(params)
        except ValidationError as exc:
            raise ToolParameterError(
                f"Tool '{name}' received invalid parameters: {_summarise_validation(exc)}",
                detail=str(exc),
            ) from exc
        result = spec.func(parsed, ctx)
        if isinstance(result, BaseModel):
            result = result.model_dump()
        if not isinstance(result, dict):
            raise UnexpectedToolOutput(
                f"Tool '{name}' returned {type(result).__name__} instead of a structured result",
                detail=repr(result)[:300],
            )
        try:
            return spec.output_model.model_validate(result).model_dump()
        except ValidationError as exc:
            raise UnexpectedToolOutput(
                f"Tool '{name}' returned an unexpected result shape: {_summarise_validation(exc)}",
                detail=str(exc),
            ) from exc


def _summarise_validation(exc: ValidationError) -> str:
    parts = []
    for err in exc.errors()[:4]:
        loc = ".".join(str(p) for p in err["loc"]) or "<root>"
        parts.append(f"{loc}: {err['msg']}")
    more = len(exc.errors()) - 4
    return "; ".join(parts) + (f" (+{more} more)" if more > 0 else "")


def walk_params(value: Any, path: str = "") -> list[tuple[str, Any]]:
    """Flatten a params structure into ``(path, leaf)`` pairs.

    Dict keys and list indexes form the dotted path (``derive.shortfall``,
    ``rules.0.invalid_when``) so they can be matched against
    :attr:`ToolSpec.expression_params` globs.
    """
    out: list[tuple[str, Any]] = []
    if isinstance(value, dict):
        for k, v in value.items():
            out.extend(walk_params(v, f"{path}.{k}" if path else str(k)))
    elif isinstance(value, list):
        for i, v in enumerate(value):
            out.extend(walk_params(v, f"{path}.{i}" if path else str(i)))
    else:
        out.append((path, value))
    return out
